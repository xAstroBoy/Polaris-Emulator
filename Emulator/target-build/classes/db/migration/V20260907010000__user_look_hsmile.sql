-- HSmile look libraries (2026-09-06 import): banners, stands (tiles), overlays (filters), wallpapers,
-- infostand borders, ornaments, name effects and name icons are served by NAME from
-- <image.library.url>/<folder>/<name>.gif, so infostand_backgrounds learns the asset name and the
-- per-ornament geometry. Ids start at 1001 in every category to stay clear of the CSS-class based
-- legacy items (0..999). New user-level fields live in user_look_extras.
ALTER TABLE `infostand_backgrounds`
    MODIFY COLUMN `category` ENUM('background','stand','overlay','card','border','ornament','name_effect','name_icon','profile_bg') NOT NULL;

ALTER TABLE `infostand_backgrounds`
    ADD COLUMN IF NOT EXISTS `name` VARCHAR(64) NOT NULL DEFAULT '' AFTER `category`,
    ADD COLUMN IF NOT EXISTS `width` INT(11) NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS `height` INT(11) NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS `margin_top` INT(11) NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS `name_color` VARCHAR(7) NOT NULL DEFAULT '';

CREATE TABLE IF NOT EXISTS `user_look_extras` (
    `user_id` INT(11) NOT NULL,
    `ornament_id` INT(11) NOT NULL DEFAULT 0,
    `name_effect_id` INT(11) NOT NULL DEFAULT 0,
    `name_icon_id` INT(11) NOT NULL DEFAULT 0,
    `profile_bg_id` INT(11) NOT NULL DEFAULT 0,
    `name_border` VARCHAR(7) NOT NULL DEFAULT '',
    `avatar_string` VARCHAR(64) NOT NULL DEFAULT '',
    PRIMARY KEY (`user_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

